#!/usr/bin/env node
// Extract TETR.IO tetromino matrices without hand-transcribing them.
// Usage: node scripts/extract-tetrio-matrix-fixtures.mjs <bundle> <output> <asset-url> <fetched-at> <sha256>
import { readFile, writeFile } from 'node:fs/promises';

const INPUT = process.argv[2];
const OUTPUT = process.argv[3];
const ASSET = process.argv[4];
const FETCHED_AT = process.argv[5];
const SHA256 = process.argv[6];
if (!INPUT || !OUTPUT || !ASSET || !FETCHED_AT || !/^[a-f0-9]{64}$/.test(SHA256 ?? '')) {
  console.error('Usage: node scripts/extract-tetrio-matrix-fixtures.mjs <bundle> <output> <asset-url> <fetched-at> <sha256>');
  process.exit(2);
}
const assetUrl = new URL(ASSET);
if (assetUrl.hostname !== 'tetr.io' || assetUrl.pathname !== '/js/tetrio.js' || !assetUrl.searchParams.get('hv')) {
  throw new Error('Source asset must be an explicit versioned TETR.IO client URL.');
}
const PIECES = ['i', 'o', 't', 's', 'z', 'j', 'l'];
const source = await readFile(INPUT, 'utf8');
const literal = extractObjectLiteralAfterKey(source, 'tetrominoes');
const allPieces = evaluateObject(literal);
const matrices = {};

for (const piece of PIECES) {
  const entry = allPieces[piece];
  if (!entry || !entry.matrix || !Array.isArray(entry.matrix.data)) {
    throw new Error('Source asset is missing matrix data for tetromino ' + piece);
  }
  const { dx, dy, data } = entry.matrix;
  if (!Number.isFinite(dx) || !Number.isFinite(dy) || data.length !== 4) {
    throw new Error('Invalid matrix offsets/orientation count for tetromino ' + piece);
  }
  const orientations = data.map((cells, orientation) => {
    if (!Array.isArray(cells) || cells.length !== 4) {
      throw new Error('Expected exactly four occupied cells for ' + piece + ' orientation ' + orientation);
    }
    const normalized = cells.map((cell) => {
      if (!Array.isArray(cell) || !Number.isFinite(cell[0]) || !Number.isFinite(cell[1])) {
        throw new Error('Malformed cell for ' + piece + ' orientation ' + orientation);
      }
      return [cell[0], cell[1]];
    });
    if (new Set(normalized.map(([x, y]) => x + ',' + y)).size !== 4) {
      throw new Error('Duplicate matrix cells for ' + piece + ' orientation ' + orientation);
    }
    return normalized;
  });
  matrices[piece.toUpperCase()] = { dx, dy, orientations };
}

const output = [
  '// Generated by scripts/extract-tetrio-matrix-fixtures.mjs. Do not edit by hand.',
  '// Source asset: ' + ASSET,
  '// Bundle SHA-256: ' + SHA256,
  '// Fetched at: ' + FETCHED_AT,
  '// Candidate data must be compared against movement snapshots before acceptance.',
  'export const TETRIO_MATRIX_SOURCE = Object.freeze({ asset: ' + JSON.stringify(ASSET) + ', fetchedAt: ' + JSON.stringify(FETCHED_AT) + ', sha256: ' + JSON.stringify(SHA256) + ' });',
  'export const TETRIO_MATRIX_REFERENCE = Object.freeze(' + JSON.stringify(matrices, null, 2) + ');',
  ''
].join('\n');
await writeFile(OUTPUT, output, 'utf8');
console.log('Extracted exact matrix fixtures for ' + PIECES.length + ' tetrominoes to ' + OUTPUT);

function extractObjectLiteralAfterKey(input, key) {
  const keyIndex = input.indexOf(key + ':');
  if (keyIndex === -1) throw new Error('Could not find ' + key + ' in the client bundle.');
  const start = input.indexOf('{', keyIndex + key.length + 1);
  if (start === -1) throw new Error('Could not find ' + key + ' object start.');
  let depth = 0;
  let quote;
  let escaped = false;
  for (let index = start; index < input.length; index += 1) {
    const char = input[index];
    if (quote !== undefined) {
      if (escaped) escaped = false;
      else if (char === '\\') escaped = true;
      else if (char === quote) quote = undefined;
      continue;
    }
    if (char === '"' || char === "'" || char === '`') { quote = char; continue; }
    if (char === '{') depth += 1;
    else if (char === '}' && --depth === 0) return input.slice(start, index + 1);
  }
  throw new Error('Could not find ' + key + ' object end.');
}

function evaluateObject(text) {
  const value = Function('"use strict"; return (' + text + ');')();
  if (!value || typeof value !== 'object' || Array.isArray(value)) {
    throw new Error('Extracted tetrominoes literal was not an object.');
  }
  return value;
}
